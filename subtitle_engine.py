
"""CineForge AI - Automatic Speech Recognition and Subtitle Engine."""

import logging
from pathlib import Path

from faster_whisper import WhisperModel


logger = logging.getLogger(__name__)

MODEL_SIZE = "base"
DEVICE = "cpu"
COMPUTE_TYPE = "int8"

_whisper_model = None


# ---------------------------------------------------------
# WHISPER MODEL
# ---------------------------------------------------------

def load_whisper_model():
    """Load the local Whisper model once."""

    global _whisper_model

    if _whisper_model is None:

        logger.info(
            "Loading Faster-Whisper model: %s",
            MODEL_SIZE
        )

        _whisper_model = WhisperModel(
            MODEL_SIZE,
            device=DEVICE,
            compute_type=COMPUTE_TYPE,
            cpu_threads=2,
            num_workers=1
        )

    return _whisper_model


# ---------------------------------------------------------
# TIMESTAMP FORMATTING
# ---------------------------------------------------------

def format_timestamp(seconds):
    """Convert seconds into SRT timestamp format."""

    milliseconds = max(
        0,
        int(round(float(seconds) * 1000))
    )

    hours = milliseconds // 3_600_000
    milliseconds %= 3_600_000

    minutes = milliseconds // 60_000
    milliseconds %= 60_000

    secs = milliseconds // 1000
    milliseconds %= 1000

    return (
        f"{hours:02}:{minutes:02}:{secs:02},"
        f"{milliseconds:03}"
    )


# ---------------------------------------------------------
# SUBTITLE TEXT FORMATTING
# ---------------------------------------------------------

def split_subtitle_text(text, max_chars=42):
    """
    Split subtitle text into readable lines.

    Keeps captions to a maximum of two lines where possible.
    """

    words = str(text or "").strip().split()

    if not words:
        return ""

    lines = []
    current_line = ""

    for word in words:

        candidate = f"{current_line} {word}".strip()

        if len(candidate) <= max_chars:

            current_line = candidate

        else:

            if current_line:
                lines.append(current_line)

            current_line = word

    if current_line:
        lines.append(current_line)

    # Keep caption blocks compact.
    if len(lines) > 2:
        lines = [
            " ".join(words[:len(words) // 2]),
            " ".join(words[len(words) // 2:])
        ]

    return "\n".join(lines)


# ---------------------------------------------------------
# VALIDATION
# ---------------------------------------------------------


def validate_subtitles(blocks):
    """Validate subtitle blocks generated by Whisper."""

    if not blocks:
        raise RuntimeError(
            "Whisper could not detect speech in the narration."
        )

    previous_end = 0.0

    for index, block in enumerate(blocks, start=1):

        if not isinstance(block, dict):
            raise RuntimeError(
                f"Invalid subtitle data type at block {index}."
            )

        start_time = block.get("start_time")
        end_time = block.get("end_time")
        content = block.get("content")

        if start_time is None or end_time is None or not content:
            raise RuntimeError(
                f"Missing subtitle data at block {index}."
            )

        try:
            start_time = float(start_time)
            end_time = float(end_time)
        except (TypeError, ValueError):
            raise RuntimeError(
                f"Invalid subtitle timing at block {index}."
            )

        if start_time < 0 or end_time <= start_time:
            raise RuntimeError(
                f"Invalid subtitle duration at block {index}."
            )

        if start_time < previous_end:
            raise RuntimeError(
                f"Overlapping subtitle timing at block {index}."
            )

        previous_end = end_time



# ---------------------------------------------------------
# SUBTITLE GENERATION
# ---------------------------------------------------------

def generate_subtitles(audio_path, output_path, language="en"):
    """
    Generate synchronized subtitles from narration audio.

    Uses Faster-Whisper speech timestamps.
    """

    audio_path = Path(audio_path).resolve()
    output_path = Path(output_path).resolve()

    if not audio_path.is_file():
        raise FileNotFoundError(
            f"Audio file not found: {audio_path}"
        )

    if audio_path.stat().st_size == 0:
        raise ValueError(
            "Narration audio file is empty."
        )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    logger.info("Starting subtitle generation.")

    model = load_whisper_model()

    segments, info = model.transcribe(
        str(audio_path),
        language=language,
        beam_size=1,
        best_of=1,
        vad_filter=True,
        word_timestamps=False,
        condition_on_previous_text=False,
        vad_parameters={
            "min_silence_duration_ms": 450,
            "speech_pad_ms": 250
        }
    )

    subtitle_blocks = []

    previous_end = 0.0

    for segment in segments:

        text = split_subtitle_text(segment.text)

        if not text:
            continue

        start_time = max(
            0.0,
            float(segment.start)
        )

        end_time = max(
            start_time,
            float(segment.end)
        )

        if end_time <= start_time:
            continue

        # Avoid overlapping caption blocks.
        start_time = max(
            start_time,
            previous_end
        )

        if end_time <= start_time:
            continue

        block = (
            f"{len(subtitle_blocks) + 1}\n"
            f"{format_timestamp(start_time)} --> "
            f"{format_timestamp(end_time)}\n"
            f"{text}"
        )

        subtitle_blocks.append({
            "content": block,
            "start_time": start_time,
            "end_time": end_time
        })

        previous_end = end_time

    validate_subtitles(subtitle_blocks)

    srt_content = "\n\n".join(
        block["content"]
        for block in subtitle_blocks
    ) + "\n"

    # Write to a temporary file first.
    temporary_path = output_path.with_name(
        output_path.stem + ".tmp.srt"
    )

    try:

        temporary_path.write_text(
            srt_content,
            encoding="utf-8-sig"
        )

        if (
            not temporary_path.is_file()
            or temporary_path.stat().st_size == 0
        ):
            raise RuntimeError(
                "Temporary subtitle file is empty."
            )

        # Replace existing subtitles only after success.
        temporary_path.replace(output_path)

    finally:

        if temporary_path.exists():
            temporary_path.unlink(missing_ok=True)

    logger.info(
        "Detected language: %s",
        info.language
    )

    logger.info(
        "Subtitle segments: %s",
        len(subtitle_blocks)
    )

    logger.info(
        "Subtitle file: %s",
        output_path
    )

    return str(output_path)
